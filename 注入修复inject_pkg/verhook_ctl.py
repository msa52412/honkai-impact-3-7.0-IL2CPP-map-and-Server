# -*- coding: utf-8 -*-
r"""verhook_ctl.py —— BH3 7.0 的 version.dll 侧加载通道（安装 / 卸载 / 编译 / 状态）

背景
----
UnityPlayer.dll 的导入表里有 VERSION.dll；`version` 不在 KnownDLLs；
SafeDllSearchMode 默认 1（应用目录优先）。
=> 把 version.dll 放到 BH3.exe 同目录，游戏就会加载我们的，而不是 system32 的。

本工具管理的三个文件：
    version.dll    我们的垫片：17 个导出全部转发到 system32\version.dll，
                   DllMain 里读 libraries.txt 逐行 LoadLibraryA，并写 verhook.log
    libraries.txt  每行一个要加载的 DLL（# 开头为注释）
    <payload>.dll  载荷，默认 bh3probe.dll（只写日志，用来验证通道）

用法
----
    python tools\verhook_ctl.py build                  # 编译垫片 + 探针
    python tools\verhook_ctl.py install                # 装进游戏目录（默认探针）
    python tools\verhook_ctl.py install --libs bh3probe.dll,other.dll
    python tools\verhook_ctl.py status                 # 看装没装、日志尾部
    python tools\verhook_ctl.py uninstall              # 清干净（会恢复 .orig 备份）

注意
----
* 安装前会检查游戏是否在跑，跑着就不动。
* 若目标位置已有同名 version.dll，先备份成 version.dll.orig，卸载时还原。
* 编译依赖 `pip install ziglang`（自带 zig，无需 MSVC）。实测 zig 0.16.0 可用。
"""

import argparse
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                     # D:\BH3\7.0
SRC = os.path.join(ROOT, "_ext", "verhook")      # 源码与产物目录
CLIENT = "BH3.exe"

SHIM = "version.dll"
LIST = "libraries.txt"
DEFAULT_LIBS = ["bh3probe.dll"]
LOGS = ["verhook.log", "bh3probe.log"]


# ------------------------------------------------------------------ 基础

def say(msg=""):
    print(msg)


def head(msg):
    print("")
    print("=" * 68)
    print("  " + msg)
    print("=" * 68)


def game_running():
    try:
        out = subprocess.run(["tasklist", "/FI", "IMAGENAME eq " + CLIENT],
                             capture_output=True, timeout=15)
        return CLIENT.lower() in (out.stdout or "").lower()
    except Exception:
        return False


def _same_file(a, b):
    """两个文件内容是否相同（用于判断 version.dll 是不是我们自己装的）。"""
    try:
        if os.path.getsize(a) != os.path.getsize(b):
            return False
        import hashlib
        with open(a, "rb") as fa, open(b, "rb") as fb:
            return hashlib.md5(fa.read()).digest() == hashlib.md5(fb.read()).digest()
    except Exception:
        return False


def zig_cc(args):
    """用 pip 装的 ziglang 调编译器（本机没有 MSVC）。"""
    cmd = [sys.executable, "-m", "ziglang", "cc"] + args
    return subprocess.run(cmd, capture_output=True, text=True)


def build_one(c_file, out_dll):
    src = os.path.join(SRC, c_file)
    dst = os.path.join(SRC, out_dll)
    if not os.path.exists(src):
        say("  [FAIL] 源文件不存在: %s" % src)
        return False
    r = zig_cc(["-target", "x86_64-windows-gnu", "-shared", "-O2",
                "-o", dst, src])
    if r.returncode != 0:
        say("  [FAIL] 编译 %s 失败" % c_file)
        for line in (r.stderr or "").splitlines():
            if ": error" in line:
                say("         " + line.strip())
        return False
    say("  [ OK ] %-14s -> %s (%d KB)"
        % (c_file, out_dll, os.path.getsize(dst) // 1024))
    return True


# ------------------------------------------------------------------ 命令

def cmd_build(ns):
    head("编译")
    ok = build_one("version.c", SHIM)
    if ns.with_probe:
        ok = build_one("bh3probe.c", "bh3probe.dll") and ok
    if ok:
        # 校验导出
        try:
            import pefile
            pe = pefile.PE(os.path.join(SRC, SHIM))
            n = len(pe.DIRECTORY_ENTRY_EXPORT.symbols)
            say("  [ OK ] %s 导出 %d 个（应为 17）" % (SHIM, n))
            pe.close()
        except Exception as e:
            say("  [WARN] 导出校验跳过: %r" % (e,))
    return 0 if ok else 1


def cmd_install(ns):
    head("安装到游戏目录")
    if game_running():
        say("  [FAIL] 游戏正在运行，先关掉再装")
        return 1

    shim_src = os.path.join(SRC, SHIM)
    if not os.path.exists(shim_src):
        say("  [FAIL] 找不到 %s，先跑 `build`" % shim_src)
        return 1

    dst_shim = os.path.join(ROOT, SHIM)
    if os.path.exists(dst_shim) and not _same_file(dst_shim, shim_src) \
            and not os.path.exists(dst_shim + ".orig"):
        shutil.copy2(dst_shim, dst_shim + ".orig")
        say("  备份原 %s -> %s.orig" % (SHIM, SHIM))
    shutil.copy2(shim_src, dst_shim)
    say("  [ OK ] %s" % dst_shim)

    libs = [x.strip() for x in (ns.libs or ",".join(DEFAULT_LIBS)).split(",") if x.strip()]
    for lib in libs:
        p = os.path.join(SRC, lib)
        if os.path.exists(p):
            shutil.copy2(p, os.path.join(ROOT, lib))
            say("  [ OK ] %s" % lib)
        else:
            say("  [WARN] 载荷不存在，只写进 libraries.txt: %s" % lib)

    with open(os.path.join(ROOT, LIST), "w", encoding="ascii", newline="\n") as f:
        f.write("# generated by verhook_ctl.py, one DLL per line\n")
        for lib in libs:
            f.write(lib + "\n")
    say("  [ OK ] %s -> %s" % (LIST, ", ".join(libs)))
    say("")
    say("  启动游戏后看：%s\\verhook.log" % ROOT)
    return 0


def cmd_uninstall(ns):
    head("从游戏目录卸载")
    if game_running():
        say("  [FAIL] 游戏正在运行，先关掉再卸")
        return 1
    for name in [SHIM, LIST, "bh3probe.dll"] + LOGS:
        p = os.path.join(ROOT, name)
        if os.path.exists(p):
            os.remove(p)
            say("  删除 %s" % name)
    orig = os.path.join(ROOT, SHIM + ".orig")
    if os.path.exists(orig):
        shutil.move(orig, os.path.join(ROOT, SHIM))
        say("  还原 %s.orig -> %s" % (SHIM, SHIM))
    say("  [ OK ] 清理完成")
    return 0


def cmd_status(ns):
    head("状态")
    say("  游戏目录: %s" % ROOT)
    for name in [SHIM, LIST, "bh3probe.dll"] + LOGS:
        p = os.path.join(ROOT, name)
        if os.path.exists(p):
            say("  [ 装 ] %-16s %d bytes" % (name, os.path.getsize(p)))
        else:
            say("  [ 无 ] %s" % name)
    say("  游戏进程: %s" % ("运行中" if game_running() else "未运行"))
    log = os.path.join(ROOT, "verhook.log")
    if os.path.exists(log):
        say("")
        say("  --- verhook.log 尾部 ---")
        with open(log, "r", encoding="utf-8", errors="replace") as f:
            for line in f.read().splitlines()[-10:]:
                say("    " + line)
    return 0


def main():
    ap = argparse.ArgumentParser(add_help=True)
    ap.add_argument("mode", nargs="?", default="status",
                    choices=["build", "install", "uninstall", "status"])
    ap.add_argument("--libs", default=None, help="逗号分隔的载荷 DLL 名")
    ap.add_argument("--with-probe", action="store_true", default=True,
                    help="build 时一并编译探针（默认开）")
    ns = ap.parse_args()
    return {"build": cmd_build, "install": cmd_install,
            "uninstall": cmd_uninstall, "status": cmd_status}[ns.mode](ns)


if __name__ == "__main__":
    sys.exit(main())
