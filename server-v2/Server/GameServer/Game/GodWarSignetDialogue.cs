    private static void ClearSignetDialogue(DeepState deep)
    {
        deep.SignetDialoguePlot = 0;
        deep.SignetDialogueFollow = 0;
    }

    private static void PrepareSignetDialogue(ChallengeRun run)
    {
        var deep = run.Deep;
        ClearSignetDialogue(deep);
        var suits = PlayableBuffRows()
            .Where(row => deep.Candidates.Contains((uint)row["BuffID"]))
            .Select(row => (uint)row["BuffSuit"]).Distinct().ToArray();
        if (suits.Length != 1 || suits[0] is < 1 or > 14)
            return;

        var suit = suits[0];
        // Door 109 starts the post-Ego sequence; its suit ID is 10.
        var dialogueIndex = suit >= 10 ? suit - 1 : suit;
        var follow = (deep.CoreSuit == 0 ? 500100u : 500200u) + dialogueIndex;
        if (!SignetLines.TryGetValue(follow, out var lines))
            return;

        deep.SignetDialoguePlot = lines[Random.Shared.Next(lines.Length)].Plot;
        deep.SignetDialogueFollow = follow;
    }

    private static GodWarEventInfo SignetDialogueEvent(ChallengeRun run)
    {
        var deep = run.Deep;
        if (SignetLines.TryGetValue(deep.SignetDialogueFollow, out var lines))
        {
            var line = lines.FirstOrDefault(line => line.Plot == deep.SignetDialoguePlot);
            if (line.Event == 0)
                line = lines[0];
            return Event(line.Event, line.Plot);
        }
        return SelectionEvent(run);
    }
